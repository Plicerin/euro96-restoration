"""Rebuild an isolated ball engine from original bodies and verified OMF constants.
No original files are edited; no DOS object code is linked into the Windows build.
"""
from pathlib import Path
import hashlib,json,re,struct,sys
from omf import Object

BALL_ROUTINES=['get_angle','get_xydis_from_ang','get_s_angle','get_zdis_from_ang',
 'stop_ball_spin','swerve_xyz','inc_swerve','get_aftert_spin','add_spin_fx',
 'move_ball','grav_ball','ball_friction','roll_ball','ball_trajectory','get_ball_zone',
 'launch_ball','reset_shot']

def routine(text,name):
 m=re.search(r'^(?:void|float|int|short|char)\s+'+name+r'\s*\([^;]*?\)(?:\s|//[^\n]*\n)*\{',text,re.M)
 if not m:raise ValueError('Missing routine '+name)
 # Source in this extraction set has no brace characters in strings or comments.
 p=m.end();depth=1
 while depth and p<len(text):depth+=(text[p]=='{')-(text[p]=='}');p+=1
 if depth:raise ValueError('Unterminated routine '+name)
 return text[m.start():p],text[:m.start()].count('\n')+1

def generate(source,out,report):
 expected={'BALL.OBJ':'f8dd68af5519f5fd70085de559d57418f24beea6dea9f9fb2cfd8e4627e76ec5','FOOTBALL.OBJ':'80386fd58625e1a5a8491cdf700096af782636923ba40b778746274c8663430a'}
 for name,digest in expected.items():
  if hashlib.sha256((source/name).read_bytes()).hexdigest()!=digest:raise ValueError('Unsupported preserved object '+name)
 ball=Object(source/'BALL.OBJ');football=Object(source/'FOOTBALL.OBJ');football_fixups=football.fixups()
 code=ball.segments[1]['data'];const=ball.segments[2]['data']
 # Pin instruction encodings as well as reading their immediate values. Fail closed on variant objects.
 def immediate(offset,prefix,fmt):
  if bytes(code[offset:offset+len(prefix)])!=prefix:raise ValueError('Unexpected BALL.OBJ instruction at '+hex(offset))
  return struct.unpack_from('<'+fmt,code,offset+len(prefix))[0]
 constants={
  'AIR_FRICTION':(immediate(0xa04,b'\xc7\x45\xfc','f'),'_TEXT+0xa07','float'),
  'GRND_FRICTION':(immediate(0xa0d,b'\xc7\x45\xfc','f'),'_TEXT+0xa10','float'),
  'MAX_WIND':(immediate(0xa51,b'\x81\x7d\xf8','f'),'_TEXT+0xa54','float'),
  'PI':(struct.unpack_from('<d',const,8)[0],'CONST+0x8','double'),
  'SW_HOLD_FACTOR':(struct.unpack_from('<d',const,0x44)[0],'CONST+0x44','double'),
  'IN_AIR_SPIN':(struct.unpack_from('<d',const,0x84)[0],'CONST+0x84','double'),
  'GOAL_KICK_BR':(immediate(0xcb1,b'\x83\xf8','B'),'_TEXT+0xcb3','int'),
  'KP_A':(immediate(0xcc6,b'\x83\x3d\0\0\0\0','B'),'_TEXT+0xccc','int'),
  'KP_B':(immediate(0xce5,b'\x83\x3d\0\0\0\0','B'),'_TEXT+0xceb','int'),
 }
 # Catch accidental corruption or unsupported source/object variants in the constant pool.
 if constants['PI'][0]!=3.1415926536 or constants['SW_HOLD_FACTOR'][0]!=4.0 or constants['IN_AIR_SPIN'][0]!=-0.2:
  raise ValueError('Unexpected constant pool')
 selected=[]
 for filename,names in [('BALL.CPP',BALL_ROUTINES),('MATHS.CPP',['calc_dist'])]:
  text=(source/filename).read_text(encoding='latin1')
  for name in names:
   body,line=routine(text,name);selected.append((filename,name,body,line))
 identifiers=set(re.findall(r'\b[A-Za-z_]\w*\b','\n'.join(s[2] for s in selected)))
 identifiers.update(['pitch_len','pitch_wid','cntspot_x','cntspot_y','goal_height','goal_depth','post_width','prat'])
 types={'a':('char','b'),'c':('signed char','b'),'b':('float','f'),'s':('short','h'),'i':('int','i'),'us':('unsigned short','H'),'ui':('unsigned int','I'),'uc':('unsigned char','B')}
 scalar=[];state=[]
 for symbol in football.publics:
  m=re.fullmatch(r'W\?(\w+)\$n(\w+)',symbol['name'])
  if not m or m[2] not in types:continue
  name,encoded=m.groups();ctype,fmt=types[encoded];segment=football.segments[symbol['segment']];offset=symbol['offset'];size=struct.calcsize('<'+fmt)
  if any(f['segment']==symbol['segment'] and offset<=f['offset']<offset+size for f in football_fixups):raise ValueError('Relocated scalar '+name)
  value=football.value(name,fmt)
  item=dict(name=name,type=ctype,value=value,segment=segment['name'],offset=offset,bytes=bytes(segment['data'][offset:offset+size]).hex(),storage='BSS' if segment['cls']=='BSS' else 'initialized')
  scalar.append(item)
  if name in identifiers:
   literal=repr(value)+('f' if ctype=='float' else '')
   state.append(f'    {ctype} {name} = {literal};')
 found={s['name'] for s in scalar}
 external_scalar={m[1] for n in ball.externs if (m:=re.fullmatch(r'W\?(\w+)\$n[abcsi]+',n))}
 missing=(identifiers&external_scalar)-found
 if missing:raise ValueError('Missing global definitions '+str(missing))
 decls=[s[2].split('{',1)[0].strip()+';' for s in selected]
 header='''// Generated by tools/restore_ball.py; original bodies are in ball_original.cpp.
#pragma once
#include <array>
namespace actua::original {
struct UserVector { float x=0,y=0; char m=0,f=0; };
class BallEngine {
public:
    BallEngine();
'''+ '\n'.join(state)+'''
    // EXTERNS.H's user_vectors layout; only user 1 is driven by the native sandbox.
    std::array<UserVector,20> users_dir{};
    // Owned, bounded event storage: prediction copies never share audio state.
    struct SoundEvent {int id=0;float x=0,y=0;};
    std::array<SoundEvent,128> sound_events{};
    unsigned sound_count=0, sound_dropped=0;
    int bounce_events=0, last_sound=-1;
    void play_fx(int sound,float x,float y) {
        if(prediction)return;
        ++bounce_events;last_sound=sound;
        if(sound_count<sound_events.size())sound_events[sound_count++]={sound,x,y};
        else ++sound_dropped;
    }
'''+ '\n'.join('    '+d for d in decls)+'''\n};\n}\n'''
 parts=['// Generated original routine bodies; only function scope is adapted.', '#include "ball_original.hpp"','#include <cmath>', 'namespace actua::original {', '#define ABS(x) ((x)<0?-(x):(x))','constexpr int FALSE=0;','constexpr int PS_SOFTBOUNCE=13, PS_HARDBOUNCE=14;']
 for name,(value,location,ctype) in constants.items():parts.append(f'constexpr {ctype} {name} = {repr(value)}'+('f' if ctype=='float' else '')+f'; // BALL.OBJ {location}')
 for filename,name,body,line in selected:
  scoped=re.sub(r'^(\w+)\s+'+name+r'\b',r'\1 BallEngine::'+name,body,count=1)
  parts.extend([f'#line {line} "{filename}"',scoped])
 parts.extend(['#undef ABS','}'])
 out.mkdir(parents=True,exist_ok=True)
 (out/'ball_original.hpp').write_text(header,encoding='utf-8')
 (out/'ball_original.cpp').write_text('\n'.join(parts)+'\n',encoding='utf-8')
 report.parent.mkdir(parents=True,exist_ok=True)
 report.write_text(json.dumps(dict(
  inputs={name:hashlib.sha256((source/name).read_bytes()).hexdigest() for name in ['BALL.CPP','BALL.OBJ','FOOTBALL.OBJ','MATHS.CPP']},
  constants={k:dict(value=v[0],location=v[1],type=v[2]) for k,v in constants.items()},
  routines=[dict(file=f,name=n,line=l,sha256=hashlib.sha256(b.encode()).hexdigest()) for f,n,b,l in selected],
  globals=scalar,
  caveats=['Scalar data only; BSS values precede runtime initialization.','The object snapshot is evidence for these routines, not proof all loose sources match.','Original x87 and native floating point may differ in low bits.']),indent=2)+'\n',encoding='utf-8')
 print(f'Restored {len(selected)} original routines, {len(state)} engine fields; inventoried {len(scalar)} scalar globals.')

if __name__=='__main__':generate(*map(Path,sys.argv[1:]))
